def changed(diff_lines):
    """(removed, added): the lines of a unified diff that start with - or + (file headers excluded)."""
    rem = sum(1 for ln in diff_lines if ln.startswith("-") and not ln.startswith("---"))
    add = sum(1 for ln in diff_lines if ln.startswith("+") and not ln.startswith("+++"))
    return rem, add


def counts(diff_lines):
    return "%d lines removed, %d added" % changed(diff_lines)


def _before_lv(name):
    ps, i = pt.find(name, "LoopVectorizePass")
    return pt.strip_debug(pt.ir_text(ps[i]["before"])).splitlines()


def ir_diffs():
    files = {}
    for a, b, tag in [("pipe_c18_fast", "pipe_c19_fast", "c18_c19"), ("pipe_c19_fast", "pipe_c231_fast", "c19_c231")]:
        ta, tb = _before_lv(a), _before_lv(b)
        d = list(difflib.unified_diff(ta, tb, a.replace("pipe_", ""), b.replace("pipe_", ""), lineterm="", n=2))
        files["ir_diff_before_loopvectorize_%s.txt" % tag] = (
            "# IR the loop vectorizer receives (kernel function only, debug metadata removed), %s -> %s\n"
            "# %d lines (%s), %d lines (%s); %s\n" % (a, b, len(ta), a, len(tb), b, counts(d)) + "\n".join(d) + "\n")
    for name in ("c18_fast", "c19_fast", "c22_fast", "c231_fast"):
        files["ir_before_loopvectorize_%s.ll" % name] = "\n".join(_before_lv("pipe_" + name)) + "\n"
    return files


