def loads_text():
    out = ["# Pointer loads (`load ptr`) inside the innermost loop, after each function-level pass where the count or the block count changes,",
           "# for the passes that run before LoopVectorizePass (the innermost loop is the smallest natural loop that contains a store)",
           "# (the size of a vector is two pointer loads and a subtraction; inside the loop it is recomputed every iteration)", ""]
    for n in ("pipe_c19_fast", "pipe_c22_fast", "pipe_c231_fast", "pipe_ctrunk_fast"):
        out.append("== %s" % n)
        last = None
        for idx, nm, nb, ld in loadtrack.track(n):
            if (nb, ld) != last:
                out.append("  after pass #%d %-34s innermost loop: %d blocks, %d pointer loads inside" % (idx, nm, nb, ld))
                last = (nb, ld)
        out.append("")
    return "\n".join(out) + "\n"


