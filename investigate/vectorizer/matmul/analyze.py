def umin_text():
    out = ["# The first pass whose output contains a clamped bound (`llvm.umin`) for the kernel function",
           "# (a clamp built from the size checks means the checks were turned into a bound on the trip count)", ""]
    for name in ("pipe_c18_fast", "pipe_c19_fast", "pipe_c20_fast", "pipe_c21_fast", "pipe_c22_fast", "pipe_c22_nopred",
                 "pipe_c231_fast", "pipe_ctrunk_fast", "pipe_emul_c18_abc", "pipe_hoist_c231", "pipe_restrict_c231"):
        hit = None
        for idx, p in enumerate(pt.passes(name)):
            if "llvm.umin" in pt.ir_text(p["after"]) and "llvm.umin" not in pt.ir_text(p["before"]):
                hit = "#%d %s" % (idx, p["name"].split(" on ")[0])
                break
        ps, i = pt.find(name, "LoopVectorizePass")
        out.append("%-20s first appears in the output of: %-34s | in the IR handed to LoopVectorizePass: %s" % (
            name, hit or "(never)", "yes" if "llvm.umin" in pt.ir_text(ps[i]["before"]) else "no"))
    return "\n".join(out) + "\n"


def _shape(name):
    """The IR handed to the vectorizer with value names, labels, metadata and comments removed."""
    out = []
    for ln in _before_lv(name):
        s = ln.strip()
        if not s or s.startswith("define"):
            continue
        if re.match(r"^\d+:", s):
            out.append("<label>")
            continue
        s = re.sub(r"%[A-Za-z0-9_.$-]+", "%v", s)
        s = re.sub(r"label %v", "label", s)
        s = re.sub(r", !(prof|llvm\.loop|tbaa)[ ]![0-9]+", "", s)
        s = re.sub(r"; preds = .*$", "", s)
        out.append(re.sub(r"\s+", " ", s))
    return out


