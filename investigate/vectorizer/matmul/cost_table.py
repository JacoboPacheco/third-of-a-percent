"""Per-instruction costs the loop vectorizer printed for VF 1 (scalar) and VF 4, from the saved debug answers.

    python cost_table.py                 # writes derived/cost-table.md
    python cost_table.py --check         # fails when derived/cost-table.md is not what the raw files give
"""
import os
import re
import sys

import ce

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "derived", "cost-table.md")
ROWS = [("dbg_a18_fast", "clang 18.1.0 (assertions), FAST, k08"), ("dbg_a19_fast", "clang 19.1.0 (assertions), FAST, k08"),
        ("dbg_a20_fast", "clang 20.1.0 (assertions), FAST, k08"), ("dbg_a22_fast", "clang 22.1.0 (assertions), FAST, k08")]
PAT = re.compile(r"Found an estimated cost of (\d+) for VF (\d+) For instruction:\s+(.*?)(, !dbg.*)?$")


def short(inst):
    """A label that is stable across compilers: the opcode and the first operand type."""
    m = re.match(r"(%[\w.]+) = (\w+)(?: nuw| nsw| inbounds| exact)* (\w+)?", inst)
    if inst.startswith("br "):
        return "br"
    if inst.startswith("store"):
        return "store i32"
    if m:
        name = m.group(1)
        op = m.group(2)
        extra = m.group(3) or ""
        if op == "icmp":
            return "%s (icmp %s)" % (name.split(".")[0] if "cmp" in name else name, extra)
        return "%s (%s)" % (name.rstrip("0123456789."), op)
    return inst[:30]


def table(name):
    t = ce.stderr_text(ce.load(name))
    vf = {1: [], 4: []}
    seen = set()
    for ln in t.splitlines():
        m = PAT.search(ln)
        if m and int(m.group(2)) in vf:
            key = (int(m.group(2)), m.group(3))
            if key in seen:  # newer compilers print the same cost list more than once; keep the first
                continue
            seen.add(key)
            vf[int(m.group(2))].append((int(m.group(1)), m.group(3)))
    totals = {k: sum(c for c, _ in v) for k, v in vf.items()}
    scalar = re.search(r"Scalar loop costs: (\d+)", t)
    v4 = re.search(r"Vector loop of width 4 costs: (\d+)", t)
    return vf, totals, int(scalar.group(1)) if scalar else None, int(v4.group(1)) if v4 else None


def render():
    out = ["# Per-instruction costs printed by the loop vectorizer (-mllvm -debug-only=loop-vectorize)", "",
           "Generated by `cost_table.py` from `raw/dbg_*_fast.json`. Units are the cost model's own (not cycles).",
           "VF 4 'per lane' is the sum divided by 4 with integer division, as the vectorizer prints it.", ""]
    for name, label in ROWS:
        vf, totals, scalar, v4 = table(name)
        out.append("## %s (`raw/%s.json`)" % (label, name))
        out.append("")
        out.append("| instruction | VF 1 | VF 4 |")
        out.append("|---|---|---|")
        c4 = {inst: c for c, inst in vf[4]}
        for c1, inst1 in vf[1]:
            if c1 == 0 and c4.get(inst1, 0) == 0:
                continue
            out.append("| `%s` | %d | %s |" % (re.sub(r"\s+", " ", inst1)[:70], c1, c4.get(inst1, "-")))
        out.append("| **sum** | **%d** | **%d** |" % (totals[1], totals[4]))
        out.append("")
        out.append("Printed: `Scalar loop costs: %s`, `Vector loop of width 4 costs: %s` (sum %d / 4 = %d)." % (
            scalar, v4, totals[4], totals[4] // 4))
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(text)
