def build_line(name):
    """The `clang version ...` line of an answer made with -v."""
    return next((ln.strip() for ln in ce.stderr_text(ce.load(name)).splitlines() if ln.startswith("clang version")), "(no version line)")


def installed_dir(name):
    return next((ln.split(": ", 1)[1].strip() for ln in ce.stderr_text(ce.load(name)).splitlines() if ln.startswith("InstalledDir")), "(none)")


def revision(name):
    """The first 10 hex digits of the LLVM revision in the answer's `clang version` line, or None."""
    m = re.search(r"llvm-project\.git ([0-9a-f]{40})", build_line(name))
    return m.group(1)[:10] if m else None


def tbaa_text():
    """Access type of the TBAA tag on every `load ptr` in the optimized IR of the kernel function (raw/emitfull_*.json)."""
    out = ["# `load ptr` instructions of kern_k08_matmul in the optimized IR (-O2 -emit-llvm, FAST): the access type of their !tbaa tag", ""]
    for n in ("emitfull_c19_fast", "emitfull_c22_fast", "emitfull_c231_fast"):
        lines = ce.asm_text(ce.load(n)).splitlines()
        md = {}
        for ln in lines:
            m = re.match(r"^!(\d+) = (.*)$", ln)
            if m:
                md[m.group(1)] = m.group(2)
        start = next(i for i, ln in enumerate(lines) if ln.startswith("define") and "kern_k08_matmul" in ln)
        end = next(i for i in range(start, len(lines)) if lines[i] == "}")
        kinds = {}
        total = 0
        for ln in lines[start:end]:
            if "= load ptr," not in ln:
                continue
            total += 1
            m = re.search(r"!tbaa !(\d+)", ln)
            if m:
                t = re.match(r"!\{!(\d+), !(\d+), i64 \d+", md[m.group(1)])
                kind = "tagged, access type `%s`" % re.search(r'!"([^"]*)"', md[t.group(2)]).group(1)
            else:
                kind = "no !tbaa tag"
            kinds[kind] = kinds.get(kind, 0) + 1
        out.append("%-20s %d `load ptr`: %s" % (n, total, "; ".join("%d %s" % (v, k) for k, v in sorted(kinds.items()))))
    return "\n".join(out) + "\n"


def short_outcome(c):
    if c["status"] == "vectorized":
        return "vectorized (%s)" % c["detail"]
    if "cost-model" in c["detail"]:
        return "not vectorized: cost model, not beneficial"
    if "condition load" in c["detail"]:
        return "not vectorized: early-exit loop with a store"
    if "complex writes" in c["detail"]:
        return "not vectorized: early-exit loop with complex writes"
    return "not vectorized: " + c["detail"]


