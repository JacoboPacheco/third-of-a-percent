DER = os.path.join(HERE, "derived")
SKIP_GROUPS = {"paths", "paths2", "emit", "emitfull"}
REMARK = re.compile(r"^<source>:(\d+):\d+: remark: (.*?) \[-Rpass[-a-z]*=loop-vectorize\]")


def loop_line(src_rel):
    with open(os.path.join(HERE, src_rel), encoding="utf-8") as f:
        for i, ln in enumerate(f, 1):
            if "// LOOP" in ln:
                return i
    raise ValueError(src_rel)


def classify(name, src_rel):
    rec = ce.load(name)
    resp = rec["response"]
    if resp.get("code") != 0:
        first = next((ln for ln in ce.stderr_text(rec).splitlines() if "error:" in ln), "")
        return {"status": "compile error", "detail": re.sub(r"^.*error: ", "", first)[:90], "asm": 0, "ud2": 0, "simd": 0}
    line = loop_line(src_rel)
    rem = []
    for ln in ce.stderr_text(rec).splitlines():
        m = REMARK.match(ln)
        if m and int(m.group(1)) == line:
            rem.append(m.group(2))
    vec = [r for r in rem if r.startswith("vectorized loop")]
    asm = [x.get("text", "") for x in resp.get("asm") or []]
    ud2 = sum(1 for a in asm if a.strip().startswith("ud2"))
    simd = sum(1 for a in asm if re.search(r"\b[xy]mm\d+\b", a) and not re.match(r"\s*(movd|movq)\b", a))
    if vec:
        m = re.search(r"width: (\d+), interleaved count: (\d+)", vec[0])
        status, detail = "vectorized", "width %s, interleave %s" % (m.group(1), m.group(2))
    else:
        status = "not vectorized"
        detail = "; ".join(r for r in rem if "interleaving" not in r)[:110] or "(no remark at the loop)"
    return {"status": status, "detail": detail, "asm": len(asm), "ud2": ud2, "simd": simd}


def outcomes():
    rows = []
    for name, (group, cid, src, args, pipe, filters) in rr.MANIFEST.items():
        if group in SKIP_GROUPS or ce.load(name) is None:
            continue
        c = classify(name, src)
        rows.append((name, group, cid, c))
    return rows


def tsv(rows):
    out = ["name\tgroup\tcompiler_id\tstatus\tdetail\tasm_lines\tud2\tsimd_lines"]
    for name, group, cid, c in rows:
        out.append("\t".join([name, group, cid, c["status"], c["detail"], str(c["asm"]), str(c["ud2"]), str(c["simd"])]))
    return "\n".join(out) + "\n"


def by_name(rows):
    return {r[0]: r[3] for r in rows}


def cell(c):
    if c["status"] == "vectorized":
        return "vectorized (%s)" % c["detail"]
    if c["status"] == "compile error":
        return "compile error: %s" % c["detail"]
    return "not vectorized: %s" % c["detail"]


def lv_numbers(name):
    t = ce.stderr_text(ce.load(name))

    def g(pat):
        m = re.search(pat, t)
        return m.group(1) if m else "-"

    cmp4 = re.findall(r"Found an estimated cost of (\d+) for VF 4 For instruction:\s+%cmp\S* = icmp", t)
    uniform = bool(re.search(r"Found uniform instruction:\s+%cmp\.i\d+ = icmp", t))
    return {"scalar": g(r"Scalar loop costs: (\d+)"), "vf2": g(r"Vector loop of width 2 costs: (\d+)"),
            "vf4": g(r"Vector loop of width 4 costs: (\d+)"), "cmp4": "/".join(cmp4[:2]) or "-", "uniform": "yes" if uniform else "no"}


def epilogue_reasons(name):
    """The reasons the vectorizer logs for requiring a scalar epilogue (distinct, in order of first appearance)."""
    out = []
    for m in re.finditer(r"LV: Loop requires scalar epilogue: (.*)", ce.stderr_text(ce.load(name))):
        if m.group(1).strip() not in out:
            out.append(m.group(1).strip())
    return out


def mode_macro(name):
    """The libc++ hardening macro on the saved request's command line."""
    m = re.search(r"-D(_LIBCPP_\w+(?:=\S+)?)", ce.load(name)["request"]["options"]["userArguments"])
    return m.group(1) if m else "-"


def check_kind(name, c):
    """What the bounds check compiled to in the saved assembly."""
    if c["ud2"]:
        return "trap (`ud2`)"
    if "__libcpp_verbose_abort" in ce.asm_text(ce.load(name)):
        return "call of `__libcpp_verbose_abort`, no `ud2`"
    return "-"


